import java.util.Properties

plugins {
    id("com.android.application")
    id("org.jetbrains.kotlin.android")
    id("rust")
}

val tauriProperties = Properties().apply {
    val propFile = file("tauri.properties")
    if (propFile.exists()) {
        propFile.inputStream().use { load(it) }
    }
}

android {
    compileSdk = 36
    namespace = "com.langyo.wowsp"
    defaultConfig {
        // LAN pairing (phone ↔ desktop replay/game-data sync) is plain HTTP
        // v1 by design, so RELEASE builds need cleartext too — the default
        // "false" would make every pairing call fail on a signed APK. The
        // debug buildType's override stays for clarity.
        manifestPlaceholders["usesCleartextTraffic"] = "true"
        applicationId = "com.langyo.wowsp"
        minSdk = 24
        targetSdk = 36
        versionCode = tauriProperties.getProperty("tauri.android.versionCode", "1").toInt()
        versionName = tauriProperties.getProperty("tauri.android.versionName", "1.0")
    }
    buildTypes {
        getByName("debug") {
            manifestPlaceholders["usesCleartextTraffic"] = "true"
            isDebuggable = true
            isJniDebuggable = true
            isMinifyEnabled = false
            packaging {                jniLibs.keepDebugSymbols.add("*/arm64-v8a/*.so")
                jniLibs.keepDebugSymbols.add("*/armeabi-v7a/*.so")
                jniLibs.keepDebugSymbols.add("*/x86/*.so")
                jniLibs.keepDebugSymbols.add("*/x86_64/*.so")
            }
        }
        getByName("release") {
            isMinifyEnabled = true
            proguardFiles(
                *fileTree(".") { include("**/*.pro") }
                    .plus(getDefaultProguardFile("proguard-android-optimize.txt"))
                    .toList().toTypedArray()
            )
        }
    }
    kotlinOptions {
        jvmTarget = "1.8"
    }
    buildFeatures {
        buildConfig = true
    }
    androidResources {
        // The mobile bundle ships the resource pack inside the frontend
        // (WOWSP_MOBILE_BUNDLE=1 keeps the ~1.1 GB of .glb in dist), which
        // tauri embeds into libwowsp_tauri.so itself — aapt never sees the
        // GLBs today. This keeps any asset that DOES land in the aapt asset
        // dir STORED: deflating incompressible GLB data multiplies packaging
        // time and memory for ~0 size win.
        noCompress.add("glb")
    }
}

